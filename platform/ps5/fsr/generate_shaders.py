"""Embed licensed AMD FSR1 headers and emit exact private provisioning requests."""
import argparse
import hashlib
from pathlib import Path
import struct

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]


def sources():
    vertex = '''struct VSOut { float4 position : SV_Position; };
VSOut vs_main(uint id : SV_VertexID) {
    float2 p = float2((id << 1) & 2, id & 2);
    VSOut o; o.position = float4(p * float2(2,-2) + float2(-1,1), 0, 1); return o;
}
'''
    common = '''#define A_GPU 1
#define A_HLSL 1
'''
    portability = (HERE / "ffx_a.h").read_text()
    fsr = (HERE / "ffx_fsr1.h").read_text()
    bindings = '''
[[vk::binding(0, 2)]] Texture2D<float4> sc2_input : register(t0);
[[vk::binding(0, 2)]] SamplerState sc2_sampler : register(s0);
[[vk::binding(0, 3)]] cbuffer Params : register(b0) { float4 sc2_sizes; float4 sc2_options; };
'''
    easu = common + '#define FSR_EASU_F 1\n' + portability + '\n' + bindings + fsr + '''
AF4 FsrEasuRF(AF2 p) { return sc2_input.GatherRed(sc2_sampler, p); }
AF4 FsrEasuGF(AF2 p) { return sc2_input.GatherGreen(sc2_sampler, p); }
AF4 FsrEasuBF(AF2 p) { return sc2_input.GatherBlue(sc2_sampler, p); }
float4 ps_main(float4 position : SV_Position) : SV_Target0 {
    uint4 c0,c1,c2,c3;
    FsrEasuCon(c0,c1,c2,c3, sc2_sizes.x,sc2_sizes.y,sc2_sizes.x,sc2_sizes.y,sc2_sizes.z,sc2_sizes.w);
    float3 result; FsrEasuF(result, uint2(position.xy), c0,c1,c2,c3);
    return float4(result,1);
}
'''
    rcas = common + '#define FSR_RCAS_F 1\n' + portability + '\n' + bindings + fsr + '''
AF4 FsrRcasLoadF(ASU2 p) {
    return sc2_input.Load(int3(clamp(p, int2(0,0), int2(sc2_sizes.zw)-1),0));
}
void FsrRcasInputF(inout AF1 r,inout AF1 g,inout AF1 b) {}
float4 ps_main(float4 position : SV_Position) : SV_Target0 {
    uint4 c; FsrRcasCon(c,sc2_options.x);
    float3 result; FsrRcasF(result.r,result.g,result.b,uint2(position.xy),c);
    return float4(result,1);
}
'''
    return {"vertex": vertex, "easu": easu, "rcas": rcas}


def request(source, entry, vertex):
    def text(value):
        data = value.encode()
        return struct.pack('<I', len(data)) + data
    return (b'SC2REQ01' + struct.pack('<II', 0 if vertex else 4, 0) + text(entry)
            + struct.pack('<I', 0) + text(source))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--requests', type=Path)
    args = parser.parse_args()
    shaders = sources()
    header = ('/* Generated by platform/ps5/fsr/generate_shaders.py.\n'
              ' AMD FSR1 MIT notices are preserved verbatim in embedded headers. */\n#pragma once\n')
    for name, source in shaders.items():
        header += f'inline constexpr const char kSc2Fsr_{name}[] = R"SC2FSR({source})SC2FSR";\n'
    (ROOT / 'runtime/sc2_fsr_shaders.h').write_text(header, encoding='utf-8', newline='\n')
    if args.requests:
        folder = args.requests.resolve()
        if not folder.is_relative_to((ROOT / 'private').resolve()):
            parser.error('shader requests must remain inside private/')
        folder.mkdir(parents=True, exist_ok=True)
        for name, source in shaders.items():
            data = request(source, 'vs_main' if name == 'vertex' else 'ps_main', name == 'vertex')
            (folder / (hashlib.sha256(data).hexdigest() + '.request')).write_bytes(data)


if __name__ == '__main__':
    main()
